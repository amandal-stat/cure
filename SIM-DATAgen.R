generate_replicates <- function(R = 100, sim = 1, seed = 123) {
  
  settings <- list(
    `1` = list(N=50, lambda_ni=20, frailty="gamma",    beta_d=beta_true,   lam=lambda_cens_1),
    `2` = list(N=50, lambda_ni=20, frailty="stable",   beta_d=beta_stable, lam=lambda_cens_2),
    `3` = list(N=50, lambda_ni=20, frailty="additive", beta_d=beta_add,    lam=lambda_cens_3),
    `4` = list(N=50, lambda_ni=3,  frailty="gamma",    beta_d=beta_true,   lam=lambda_cens_1)
  )
  s <- settings[[as.character(sim)]]
  
  cat(sprintf("Generating %d replicates for Simulation %d...\n", R, sim))
  set.seed(seed)
  
  replicates <- vector("list", R)
  for (r in 1:R) {
    replicates[[r]] <- generate_data(
      N             = s$N,
      lambda_ni     = s$lambda_ni,
      frailty       = s$frailty,
      beta_for_data = s$beta_d,
      lambda_cens   = s$lam
    )
    if (r %% 10 == 0) cat(sprintf("  Replicate %d / %d\n", r, R))
  }
  cat("Done.\n")
  return(replicates)
}

