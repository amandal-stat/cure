plot_km <- function(dat, title_label) {
  km_fit    <- survfit(Surv(y, delta) ~ 1, data = dat)
  km_plat   <- tail(km_fit$surv, 1)
  true_cure <- mean(is.na(dat$T_true))
  
  km_df <- data.frame(
    time  = c(0, km_fit$time),
    surv  = c(1, km_fit$surv),
    upper = c(1, km_fit$upper),
    lower = c(1, km_fit$lower)
  )
  
  ggplot(km_df, aes(x=time, y=surv)) +
    geom_ribbon(aes(ymin=lower, ymax=upper), fill="steelblue", alpha=0.15) +
    geom_step(color="steelblue", linewidth=0.9) +
    geom_hline(yintercept=km_plat,   linetype="dashed", color="#C1292E",  linewidth=0.7) +
    geom_hline(yintercept=true_cure, linetype="dotted", color="darkgreen", linewidth=0.7) +
    annotate("text", x=max(km_df$time)*0.55, y=km_plat+0.04,
             label=sprintf("KM plateau = %.3f", km_plat),
             color="#C1292E", size=3.5) +
    annotate("text", x=max(km_df$time)*0.55, y=true_cure-0.04,
             label=sprintf("True cure  = %.3f", true_cure),
             color="darkgreen", size=3.5) +
    scale_y_continuous(limits=c(0,1), breaks=seq(0,1,0.2)) +
    labs(x="Time", y="Survival Probability", title=title_label,
         subtitle=sprintf("n=%d | clusters=%d | events=%d (%.1f%%)",
                          nrow(dat), length(unique(dat$cluster)),
                          sum(dat$delta), 100*mean(dat$delta))) +
    theme_classic(base_size=12) +
    theme(plot.title    = element_text(face="bold", hjust=0.5, size=12),
          plot.subtitle = element_text(hjust=0.5, color="grey40", size=10))
}

p1 <- plot_km(dat1, "Sim 1: Multiplicative Gamma")
p2 <- plot_km(dat2, "Sim 2: Multiplicative Stable")
p3 <- plot_km(dat3, "Sim 3: Additive Gamma Frailty")
p4 <- plot_km(dat4, "Sim 4: Small Clusters")

p_combined <- (p1 + p2) / (p3 + p4) +
  plot_annotation(
    title   = "Kaplan-Meier Curves by Simulation Setting",
    caption = "Red dashed = KM plateau  |  Green dotted = True cure rate",
    theme   = theme(plot.title   = element_text(face="bold", hjust=0.5, size=14),
                    plot.caption = element_text(hjust=0.5, color="grey40"))
  )
print(p_combined)

